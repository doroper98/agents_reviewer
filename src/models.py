    # v5.5.5 — 전문 용어 주석 (문단 하단 각주). 일반 독자 우선이 본 시스템의
    # *최우선 가치* — composer 는 전문 용어·영어 표현·업계 은어를 평이한 우리말로
    # 바꾸고, 뜻을 보존하느라 *불가피하게* 남긴 용어만 그 섹션 본문 하단의 각주로
