    #  - term: 본문에 그대로 둔 전문 용어/약어 (예: 'rate limit premium')
    #  - explanation: 일반 독자가 이해할 한두 문장 풀이 (마크다운 강조 금지)
    # 비면 각주 블록 자체가 렌더 안 됨. SSOT: docs/REPORT_STYLE_GUIDE.md §0/§2.2.
    footnotes: list[dict] = Field(default_factory=list)

