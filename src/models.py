class ComposedSection(BaseModel):
    """Composer 가 자유롭게 짠 한 섹션. ``prose`` 가 본문이고, 시각화는 모두 선택적."""

    heading: str
    kicker: str = ""              # 짧은 도입구 (생략 가능)
    prose: str                     # 본문 — 마크다운 단락 자유

    @field_validator(
        "kicker", "prose", "pull_quote", "lede",
        mode="before",
    )
    @classmethod
    def _none_str_to_empty(cls, v):
        # composer LLM 이 editorial 필드에 null 박는 경우 ("" 와 의미 동일) 자동 변환.
        # v5.0.0 에서 발견된 회귀 — 2026-05-06 00:32:24 보고서 사건 (lede/pull_quote
        # 7건 None 입력 → ComposedReport 전체 reject). 의미 보존하면서 운영 회복.
        return "" if v is None else v

    # v4.2.0 — composer 가 데이터까지 직접 emit (chart-id 참조 폐기)
    # 각 dict: {"type": "donut|bar|line|gantt|network|stacked|bubble|heatmap",
    #           "title": str, "data": list|dict, "note"?: str}
    charts: list[dict] = Field(default_factory=list)

    # legacy v3.3.0 — chart-id 문자열. v4.2.0 에서 의미 잃음. 보존만 (호환).
    embedded_charts: list[str] = Field(default_factory=list)

    embedded_blocks: list[str] = Field(default_factory=list)  # BlockType 문자열
    pull_quote: str = ""
    cited_claim_ids: list[str] = Field(default_factory=list)

    # v4.5.0 — editorial 인터랙션 패턴 (LG AI Seminar 보고서 차용).
    # 모두 선택적. composer 가 *섹션 성격에 맞을 때만* emit.
    lede: str = ""
    """긴 도입 문장 (1~3문장). prose 시작 전 큰 글씨 italic 으로 표시.
    kicker 는 한 줄 라벨, lede 는 본문 흐름 도입. 둘은 역할 다름."""

    analogy: dict | None = None
    """비유 박스. 형식: {title: str, body: str}. 어려운 개념을 일상 비유로 풀어
    설명할 때만. 예: title='반도체 노광은 마치 사진이다', body='..설명..'."""

    fact_grid: list[dict] = Field(default_factory=list)
    """수치 격자 (stat tile grid). 형식: [{label: str, value: str, sublabel?: str}].
    3~6개 핵심 수치를 격자로 한눈에. 본문 prose 의 뒷받침 데이터."""

    dropcap: bool = False
    """True 시 prose 첫 문단 첫 글자가 dropcap 으로 크게 렌더. 섹션 1~2개 한정.
    남용하면 시각 피로 — 보고서 전체에서 1~2 섹션만 권장."""


